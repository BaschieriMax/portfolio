import '@testing-library/jest-dom/vitest'

// jsdom does not implement matchMedia (react-hot-toast reads prefers-reduced-motion)
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
})

beforeEach(() => {
  localStorage.clear()
})
